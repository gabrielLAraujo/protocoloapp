import { IDBFactory } from 'fake-indexeddb'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import type { LocalDb } from '../../../data/localDb'
import { photoThumbRepo } from '../../../data/photoThumbRepo'
import { updateCycleRepo, updateCycleSync } from '../../../data/updateCycleRepo'
import { json, mockFetch, problem, type Handler } from '../../../test/fetch-mock'
import { fakeLocks } from '../../../test/fakeLocks'
import { newLocalDb, newTestApi } from '../../../test/localDb'
import { createPhotoQueue, type PhotoQueue } from './photoQueue'
import { startPhotoSync, uploadPending, type PhotoSyncDeps } from './photoUploader'

const CYCLE = '5b0f7c1e-1d2a-4b3c-8d4e-000000000001'
const PROTOCOL = '5b0f7c1e-1d2a-4b3c-8d4e-0000000000aa'
const T0 = new Date('2026-10-19T12:00:00.000Z')
const fileId = (n: number) => `5b0f7c1e-1d2a-4b3c-8d4e-0000000000${String(n).padStart(2, '0')}`

// Generated bytes, never a real photo.
const generated = (seed: number) => new Blob([new Uint8Array([0xff, 0xd8, seed, 0xff, 0xd9])], { type: 'image/jpeg' })

async function seedCycle(db: LocalDb) {
  await db.transaction((tx) =>
    updateCycleSync.applyRemote(tx, {
      entity: 'update_cycle',
      id: CYCLE,
      version: 1,
      payload: { protocol_version_id: PROTOCOL, period_start: '2026-10-05', period_end: '2026-10-26', status: 'collecting', answers: {}, photos: [], sent_at: null },
      deletedAt: null,
      clientUpdatedAt: '2026-10-19T10:00:00.000000+00:00',
    }),
  )
}

/** A fake API and storage: every upload-url gives a new file id; `override` replaces routes. */
function fakeServer(override: Record<string, Handler> = {}) {
  let n = 0
  const calls = mockFetch({
    'POST /api/files/upload-url': () => {
      n++
      return json({ fileId: fileId(n), uploadUrl: `http://storage.test/upload/${n}`, expiresAt: '2026-10-19T12:10:00Z' })
    },
    ...Object.fromEntries([1, 2, 3, 4].map((i) => [`PUT /upload/${i}`, () => new Response(null, { status: 200 })])),
    ...Object.fromEntries([1, 2, 3, 4].map((i) => [`POST /api/files/${fileId(i)}/confirm`, () => new Response(null, { status: 204 })])),
    ...override,
  })
  return calls
}

let db: LocalDb
let queue: PhotoQueue
let deps: PhotoSyncDeps

beforeEach(async () => {
  db = await newLocalDb()
  await seedCycle(db)
  queue = createPhotoQueue(() => new IDBFactory())
  deps = { db, api: newTestApi(), queue, now: () => T0, makeThumbnail: async () => 'data:image/jpeg;base64,AAAA' }
})

afterEach(() => vi.unstubAllGlobals())

const add = (id: string, pose: string, seed = 1, takenAt = '2026-10-19T09:00:00.000Z') =>
  queue.add({ id, cycleId: CYCLE, pose, blob: generated(seed), takenAt })

describe('uploadPending', () => {
  it('upload-url, PUT without Authorization, confirm; then the cycle photo and the thumbnail, and the queue is empty', async () => {
    await add('p1', 'front')
    const calls = fakeServer()
    const setPhoto = vi.spyOn(updateCycleRepo, 'setPhoto')

    expect(await uploadPending(deps)).toEqual({ sent: 1, failed: 0 })

    expect(calls.map((c) => `${c.method} ${c.path}`)).toEqual(['POST /api/files/upload-url', 'PUT /upload/1', `POST /api/files/${fileId(1)}/confirm`])
    expect(JSON.parse(calls[0]!.body)).toEqual({ kind: 'photo', contentType: 'image/jpeg', sizeBytes: 5 })
    expect(calls[1]!.headers.get('content-type')).toBe('image/jpeg')
    expect(calls[1]!.headers.get('authorization')).toBeNull()
    expect(setPhoto).toHaveBeenCalledTimes(1)
    expect((await updateCycleRepo.byId(db, CYCLE))!.photos).toEqual([{ pose: 'front', fileId: fileId(1), takenAt: '2026-10-19T09:00:00.000Z' }])
    expect((await photoThumbRepo.byCycle(db, CYCLE)).get('front')).toMatchObject({ fileId: fileId(1), dataUrl: 'data:image/jpeg;base64,AAAA' })
    expect(await queue.list()).toEqual([])
  })

  it('offline (fetch rejects) keeps every photo queued and changes nothing', async () => {
    await add('p1', 'front')
    await add('p2', 'back', 2, '2026-10-19T09:01:00.000Z')
    mockFetch({}) // every request fails like a dropped connection

    expect(await uploadPending(deps)).toEqual({ sent: 0, failed: 0 })

    expect((await queue.list()).map((p) => p.id)).toEqual(['p1', 'p2'])
    expect((await updateCycleRepo.byId(db, CYCLE))!.photos).toEqual([])
  })

  it('a queue left by a closed app goes up once after the reload (Review Focus 2)', async () => {
    const factory = new IDBFactory()
    const before = createPhotoQueue(() => factory)
    await before.add({ id: 'p1', cycleId: CYCLE, pose: 'front', blob: generated(1), takenAt: '2026-10-19T09:00:00.000Z' })
    mockFetch({})
    await uploadPending({ ...deps, queue: before })
    before.close()

    const after = createPhotoQueue(() => factory)
    const calls = fakeServer()
    await uploadPending({ ...deps, queue: after })
    await uploadPending({ ...deps, queue: after })

    expect(calls.filter((c) => c.method === 'PUT')).toHaveLength(1)
    expect((await updateCycleRepo.byId(db, CYCLE))!.photos).toHaveLength(1)
    expect(await after.list()).toEqual([])
  })

  it('two simultaneous calls send once', async () => {
    await add('p1', 'front')
    const calls = fakeServer()

    const [a, b] = await Promise.all([uploadPending(deps), uploadPending(deps)])

    expect(a).toEqual({ sent: 1, failed: 0 })
    expect(b).toEqual(a)
    expect(calls.filter((c) => c.method === 'PUT')).toHaveLength(1)
  })

  it('with Web Locks, a tab that finds the lock taken sends nothing', async () => {
    await add('p1', 'front')
    const calls = fakeServer()
    const locks = fakeLocks()
    const release = await locks.hold('protocolo-photo-upload')

    expect(await uploadPending({ ...deps, locks })).toEqual({ sent: 0, failed: 0 })
    expect(calls).toHaveLength(0)

    release()
    await vi.waitFor(() => expect(locks.held.has('protocolo-photo-upload')).toBe(false))
    expect(await uploadPending({ ...deps, locks })).toEqual({ sent: 1, failed: 0 })
  })

  it('a 400 drops that photo, counts it as failed and goes on with the next', async () => {
    await add('p1', 'front')
    await add('p2', 'back', 2, '2026-10-19T09:01:00.000Z')
    let first = true
    fakeServer({
      'POST /api/files/upload-url': () => {
        if (first) {
          first = false
          return problem(400, { title: 'x' })
        }
        return json({ fileId: fileId(2), uploadUrl: 'http://storage.test/upload/2', expiresAt: '2026-10-19T12:10:00Z' })
      },
    })

    expect(await uploadPending(deps)).toEqual({ sent: 1, failed: 1 })
    expect(await queue.list()).toEqual([])
    expect((await updateCycleRepo.byId(db, CYCLE))!.photos.map((p) => p.pose)).toEqual(['back'])
  })

  it('a server error stops and keeps the photo for later', async () => {
    await add('p1', 'front')
    fakeServer({ [`POST /api/files/${fileId(1)}/confirm`]: () => problem(503, { title: 'x' }) })

    expect(await uploadPending(deps)).toEqual({ sent: 0, failed: 0 })
    expect((await queue.list()).map((p) => p.id)).toEqual(['p1'])
  })

  it('a thumbnail that cannot be made does not keep the photo queued', async () => {
    await add('p1', 'front')
    fakeServer()

    const result = await uploadPending({ ...deps, makeThumbnail: () => Promise.reject(new Error('no canvas')) })

    expect(result).toEqual({ sent: 1, failed: 0 })
    expect(await queue.list()).toEqual([])
    expect((await photoThumbRepo.byCycle(db, CYCLE)).size).toBe(0)
  })

  it('never writes to the console, whatever happens', async () => {
    const spies = (['log', 'info', 'warn', 'error', 'debug'] as const).map((m) => vi.spyOn(console, m))
    await add('p1', 'front')
    await add('p2', 'back', 2, '2026-10-19T09:01:00.000Z')
    mockFetch({})
    await uploadPending(deps)
    fakeServer({ 'POST /api/files/upload-url': () => problem(400, { title: 'x' }) })
    await uploadPending(deps)

    for (const spy of spies) expect(spy).not.toHaveBeenCalled()
  })
})

describe('startPhotoSync', () => {
  it('sends at start, after each enqueue and when the connection comes back', async () => {
    mockFetch({})
    await add('p1', 'front')
    const sync = startPhotoSync(deps)
    await sync.flush()
    expect(await queue.list()).toHaveLength(1)

    const calls = fakeServer()
    window.dispatchEvent(new Event('online'))
    await vi.waitFor(async () => expect(await queue.list()).toEqual([]))

    await sync.enqueue({ id: 'p2', cycleId: CYCLE, pose: 'back', blob: generated(2), takenAt: '2026-10-19T09:01:00.000Z' })
    await vi.waitFor(async () => expect(await queue.list()).toEqual([]))
    expect(calls.filter((c) => c.method === 'PUT')).toHaveLength(2)

    sync.stop()
  })
})
